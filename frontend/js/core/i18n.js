class I18n {
    constructor() {
        this.currentLang = localStorage.getItem('mathToolboxLang') || 'zh';
    }

    init() {
        const langSelect = document.getElementById('languageSelect');
        if (langSelect) {
            langSelect.value = this.currentLang;
            langSelect.addEventListener('change', (e) => {
                this.setLanguage(e.target.value);
            });
        }
        this.translatePage();
    }

    setLanguage(lang) {
        if (translations[lang]) {
            this.currentLang = lang;
            localStorage.setItem('mathToolboxLang', lang);
            this.translatePage();
            
            // 更新动态元素
            this.translateDynamicElements();
        }
    }
    
    translateDynamicElements() {
        // 更新百分比计算器标签
        const percentageType = document.getElementById('percentageType');
        const label1 = document.getElementById('percentageLabel1');
        const label2 = document.getElementById('percentageLabel2');
        if (percentageType && label1 && label2 && window.basicCalculators) {
            window.basicCalculators.updatePercentageLabels(percentageType.value, label1, label2);
        }

        // 更新五子棋状态
        const activeModule = document.querySelector('.module-container.active');
        if (activeModule) {
            const moduleId = activeModule.id;
            if (moduleId === 'module-gobang' && window.gobangGame) {
                window.gobangGame.updateStatus('gobangBoard', false);
            } else if (moduleId === 'module-gobang-ai' && window.gobangGame) {
                window.gobangGame.updateStatus('gobangBoardAI', true);
            } else if (moduleId === 'module-coordinate' && window.geometryTools) {
                // 更新坐标转换标签
                const typeSelect = document.getElementById('coordType');
                const label1 = document.getElementById('coordLabel1');
                const label2 = document.getElementById('coordLabel2');
                if (typeSelect && label1 && label2) {
                    if (typeSelect.value === 'cartesian') {
                        label1.textContent = this.t('coordX');
                        label2.textContent = this.t('coordY');
                    } else {
                        label1.textContent = this.t('coordR');
                        label2.textContent = this.t('thetaDegrees');
                    }
                }
            } else if (moduleId === 'module-converter' && window.unitConverter) {
                // 更新单位转换器标签
                window.unitConverter.updateUnitOptions();
            } else if (moduleId === 'module-plane-geometry' && window.geometryTools) {
                // 更新平面几何标签
                const shapeSelect = document.getElementById('planeShape');
                const inputsDiv = document.getElementById('planeInputs');
                if (shapeSelect && inputsDiv) {
                    window.geometryTools.updatePlaneInputs(shapeSelect.value, inputsDiv);
                }
            } else if (moduleId === 'module-solid-geometry' && window.geometryTools) {
                // 更新立体几何标签
                const shapeSelect = document.getElementById('solidShape');
                const inputsDiv = document.getElementById('solidInputs');
                if (shapeSelect && inputsDiv) {
                    window.geometryTools.updateSolidInputs(shapeSelect.value, inputsDiv);
                }
            }
        }
        
        // 无论当前激活的模块是什么，都更新单位转换器的标签
        if (window.unitConverter) {
            window.unitConverter.updateUnitOptions();
        }
        
        // 无论当前激活的模块是什么，都更新几何模块的标签
        if (window.geometryTools) {
            const planeShapeSelect = document.getElementById('planeShape');
            const planeInputsDiv = document.getElementById('planeInputs');
            if (planeShapeSelect && planeInputsDiv) {
                window.geometryTools.updatePlaneInputs(planeShapeSelect.value, planeInputsDiv);
            }
            const solidShapeSelect = document.getElementById('solidShape');
            const solidInputsDiv = document.getElementById('solidInputs');
            if (solidShapeSelect && solidInputsDiv) {
                window.geometryTools.updateSolidInputs(solidShapeSelect.value, solidInputsDiv);
            }
        }
    }

    t(key) {
        return translations[this.currentLang][key] || key;
    }

    translatePage() {
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (el.tagName === 'INPUT' && el.placeholder) {
                el.placeholder = this.t(key);
            } else {
                el.textContent = this.t(key);
            }
        });
    }
}

let i18n;

document.addEventListener('DOMContentLoaded', function() {
    i18n = new I18n();
    i18n.init();
});